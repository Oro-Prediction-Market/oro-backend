import { Injectable } from "@nestjs/common";
import * as PDFDocument from "pdfkit";
import { AmlAlert, AmlAlertType, AmlRiskLevel } from "./entities/aml-alert.entity";
import { AmlReport } from "./entities/aml-report.entity";
import { csvCell } from "../shared/utils/csv.util";

const COLOR = {
  GOLD: "#C9A84C",
  DARK: "#1A1A2E",
  RED: "#C62828",
  ORANGE: "#E65100",
  BLUE: "#1565C0",
  GRAY: "#757575",
  LIGHT_GRAY: "#F5F5F5",
  ROW_ALT: "#FAFAFA",
  BORDER: "#E0E0E0",
  WHITE: "#FFFFFF",
};

const ALERT_TYPE_LABELS: Record<AmlAlertType, string> = {
  [AmlAlertType.RAPID_DEPOSIT_WITHDRAWAL]: "Rapid Dep/Wd",
  [AmlAlertType.LOW_GAMBLING_RATIO]: "Low Bet Ratio",
  [AmlAlertType.HIGH_TRANSACTION_FREQUENCY]: "High Frequency",
  [AmlAlertType.NEAR_LIMIT_DEPOSITS]: "Near-Limit Deps",
};

@Injectable()
export class AmlReportService {
  generateCsv(report: AmlReport, alerts: AmlAlert[]): string {
    const header = [
      "Alert ID", "User CID", "Alert Type", "Risk Level",
      "Description", "Amount (Nu)", "Transaction Count",
      "Flagged At", "Resolved", "Resolution",
    ].join(",");

    const rows = alerts.map((a) =>
      [
        a.id,
        a.user?.dkCid ?? "N/A",
        a.alertType,
        a.riskLevel.toUpperCase(),
        a.description,
        a.totalAmount ?? "",
        a.transactionCount ?? "",
        new Date(a.createdAt).toISOString(),
        a.isResolved ? "Yes" : "No",
        a.resolution ?? "",
      ]
        .map(csvCell)
        .join(","),
    );

    const meta = [
      `# Oro Platform — AML Report`,
      `# Type: ${report.reportType.toUpperCase()}`,
      `# Period: ${this.fmtDate(report.periodFrom)} to ${this.fmtDate(report.periodTo)}`,
      `# Generated: ${this.fmtDate(report.createdAt)} by ${report.generatedByName ?? "Administrator"}`,
      `# Report ID: ${report.id}`,
      `# Total Alerts: ${report.totalAlerts} | High: ${report.highRiskCount} | Medium: ${report.mediumRiskCount} | Low: ${report.lowRiskCount}`,
      ``,
    ].join("\n");

    return meta + [header, ...rows].join("\n");
  }

  generatePdfBuffer(report: AmlReport, alerts: AmlAlert[]): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 50, size: "A4" });
      const chunks: Buffer[] = [];
      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);
      this.buildPdf(doc, report, alerts);
      doc.end();
    });
  }

  private buildPdf(doc: PDFKit.PDFDocument, report: AmlReport, alerts: AmlAlert[]): void {
    const pageW = doc.page.width;
    const pageH = doc.page.height;
    const margin = 50;
    const contentW = pageW - margin * 2;

    // Header band
    doc.rect(0, 0, pageW, 78).fill(COLOR.DARK);
    doc.fillColor(COLOR.GOLD).font("Helvetica-Bold").fontSize(20).text("ORO PLATFORM", margin, 18);
    doc.fillColor(COLOR.WHITE).font("Helvetica").fontSize(10).text("Anti-Money Laundering Report", margin, 44);
    doc.fillColor(COLOR.RED).font("Helvetica-Bold").fontSize(8).text("CONFIDENTIAL", pageW - 120, 20, { width: 80, align: "right" });
    doc.fillColor(COLOR.WHITE).font("Helvetica").fontSize(7).text("For regulatory use only", pageW - 120, 32, { width: 80, align: "right" });

    // Metadata
    const metaY = 92;
    doc.fillColor(COLOR.GRAY).font("Helvetica").fontSize(8);
    doc.text(`Report Type:  ${report.reportType.toUpperCase()}`, margin, metaY);
    doc.text(`Period:          ${this.fmtDate(report.periodFrom)} – ${this.fmtDate(report.periodTo)}`, margin, metaY + 14);
    doc.text(`Generated:     ${this.fmtDate(report.createdAt)} (Bhutan Time)`, margin, metaY + 28);
    doc.text(`Generated By: ${report.generatedByName ?? "Administrator"}`, margin, metaY + 42);
    doc.text(`Report ID:  ${report.id}`, margin + contentW / 2, metaY, { width: contentW / 2 });
    if (report.notes) doc.text(`Notes: ${report.notes}`, margin + contentW / 2, metaY + 14, { width: contentW / 2 });

    // Divider
    const divY = metaY + 62;
    doc.moveTo(margin, divY).lineTo(pageW - margin, divY).strokeColor(COLOR.GOLD).lineWidth(1).stroke();

    // Summary box
    const boxY = divY + 10;
    const boxH = 76;
    doc.rect(margin, boxY, contentW, boxH).stroke(COLOR.GOLD);
    doc.fillColor(COLOR.DARK).font("Helvetica-Bold").fontSize(9).text("EXECUTIVE SUMMARY", margin + 10, boxY + 8);

    const stats = [
      { label: "Total Alerts", value: String(report.totalAlerts), color: COLOR.DARK },
      { label: "HIGH Risk", value: String(report.highRiskCount), color: COLOR.RED },
      { label: "MEDIUM Risk", value: String(report.mediumRiskCount), color: COLOR.ORANGE },
      { label: "LOW Risk", value: String(report.lowRiskCount), color: COLOR.BLUE },
      { label: "Users Affected", value: String(report.affectedUsers), color: COLOR.DARK },
    ];
    const statW = contentW / stats.length;
    stats.forEach((s, i) => {
      doc.fillColor(s.color).font("Helvetica-Bold").fontSize(20).text(s.value, margin + i * statW, boxY + 24, { width: statW, align: "center" });
      doc.fillColor(COLOR.GRAY).font("Helvetica").fontSize(7).text(s.label, margin + i * statW, boxY + 50, { width: statW, align: "center" });
    });

    // Alerts table
    const tableStartY = boxY + boxH + 16;
    doc.fillColor(COLOR.DARK).font("Helvetica-Bold").fontSize(9).text("ALERT DETAILS", margin, tableStartY);

    if (alerts.length === 0) {
      doc.fillColor(COLOR.GRAY).font("Helvetica").fontSize(9).text("No alerts found for this period.", margin, tableStartY + 18);
      this.addFooter(doc, pageH, margin, pageW, report.id);
      return;
    }

    const cols = [
      { header: "CID", width: 85 },
      { header: "Alert Type", width: 110 },
      { header: "Risk", width: 48 },
      { header: "Amount (Nu)", width: 75 },
      { header: "Flagged At", width: 75 },
      { header: "Status", width: 57 },
    ];
    const rowHeight = 22;
    const hdrHeight = 18;
    let rowY = tableStartY + 16;
    let cx = margin;
    let page = 1;

    doc.rect(margin, rowY, contentW, hdrHeight).fill(COLOR.LIGHT_GRAY);
    cols.forEach((c) => {
      doc.fillColor(COLOR.DARK).font("Helvetica-Bold").fontSize(7.5).text(c.header, cx + 4, rowY + 5, { width: c.width - 8, lineBreak: false });
      cx += c.width;
    });
    rowY += hdrHeight;

    alerts.forEach((alert, idx) => {
      if (rowY > pageH - 80) {
        this.addFooter(doc, pageH, margin, pageW, report.id, page);
        doc.addPage();
        page++;
        rowY = 50;
        cx = margin;
        doc.rect(margin, rowY, contentW, hdrHeight).fill(COLOR.LIGHT_GRAY);
        cols.forEach((c) => {
          doc.fillColor(COLOR.DARK).font("Helvetica-Bold").fontSize(7.5).text(c.header, cx + 4, rowY + 5, { width: c.width - 8, lineBreak: false });
          cx += c.width;
        });
        rowY += hdrHeight;
      }

      if (idx % 2 === 1) doc.rect(margin, rowY, contentW, rowHeight).fill(COLOR.ROW_ALT);

      const riskColor = alert.riskLevel === AmlRiskLevel.HIGH ? COLOR.RED : alert.riskLevel === AmlRiskLevel.MEDIUM ? COLOR.ORANGE : COLOR.BLUE;
      const cells = [
        alert.user?.dkCid ?? "N/A",
        ALERT_TYPE_LABELS[alert.alertType] ?? alert.alertType,
        alert.riskLevel.toUpperCase(),
        alert.totalAmount ? Number(alert.totalAmount).toLocaleString() : "—",
        this.fmtDate(alert.createdAt),
        alert.isResolved ? "Resolved" : "Open",
      ];

      cx = margin;
      cells.forEach((cell, i) => {
        doc.fillColor(i === 2 ? riskColor : COLOR.DARK).font(i === 2 ? "Helvetica-Bold" : "Helvetica").fontSize(7)
          .text(cell, cx + 4, rowY + 8, { width: cols[i].width - 8, lineBreak: false });
        cx += cols[i].width;
      });

      doc.moveTo(margin, rowY + rowHeight).lineTo(pageW - margin, rowY + rowHeight).strokeColor(COLOR.BORDER).lineWidth(0.3).stroke();
      rowY += rowHeight;
    });

    doc.rect(margin, tableStartY + 16, contentW, rowY - tableStartY - 16).stroke(COLOR.GRAY);
    this.addFooter(doc, pageH, margin, pageW, report.id, page);
  }

  private addFooter(doc: PDFKit.PDFDocument, pageH: number, margin: number, pageW: number, reportId: string, page?: number): void {
    const y = pageH - 52;
    doc.moveTo(margin, y).lineTo(pageW - margin, y).strokeColor(COLOR.GOLD).lineWidth(0.8).stroke();
    doc.fillColor(COLOR.GRAY).font("Helvetica").fontSize(6.5)
      .text("This report is confidential and intended solely for regulatory and compliance purposes. Unauthorised disclosure is prohibited.", margin, y + 6, { align: "center", width: pageW - margin * 2 });
    doc.fillColor(COLOR.GRAY).fontSize(6.5)
      .text(`Oro Platform  ·  AML Compliance  ·  Report ID: ${reportId}${page ? `  ·  Page ${page}` : ""}`, margin, y + 18, { align: "center", width: pageW - margin * 2 });
  }

  private fmtDate(d: Date | string): string {
    return new Date(d).toLocaleDateString("en-BT", {
      day: "2-digit", month: "short", year: "numeric", timeZone: "Asia/Thimphu",
    });
  }
}
