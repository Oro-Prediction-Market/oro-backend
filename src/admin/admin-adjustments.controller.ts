/**
 * The largest single adjustment, per currency. A guard against a slipped
 * keystroke (10000 for 100.00), not a policy: anything bigger is rare enough
 * to be done as two, deliberately.
 */
export const ADJUSTMENT_MAX: Readonly<Record<string, number>> = {
  BTN: 50_000,
  USDT: 2_000,
};

/** What the customer reads in their history when no wording is given. */
export const DEFAULT_USER_NOTE = {
  credit: "Wallet credit",
  debit: "Wallet adjustment",
} as const;

export class AdjustmentPreviewDto {
  @IsUUID()
  userId!: string;

  @IsIn(["BTN", "USDT"])
  currency!: string;

  @IsNumber({ allowNaN: false, allowInfinity: false })
  amount!: number;
}

export class CreateAdjustmentDto extends AdjustmentPreviewDto {
  /** Generated by the form when it opens; a second submit of the same form writes nothing. */
  @IsUUID()
  requestId!: string;

  @IsIn(Object.keys(ADJUSTMENT_REASONS))
  reason!: AdjustmentReason;

  /** Internal: what happened and why. Never shown to the customer. */
  @IsString()
  @MinLength(5)
  @MaxLength(1000)
  note!: string;

  /** Shown to the customer in their history. Defaults to neutral wording. */
  @IsOptional()
  @IsString()
  @MaxLength(120)
  userNote?: string;

  /** What this relates to: a payment id, market id, or ticket. */
  @IsOptional()
  @IsString()
  @MaxLength(128)
  reference?: string;
}

type Checked = {
  user: Pick<User, "id" | "username" | "firstName" | "currency">;
  balance: number;
  after: number;
};

/**
 * Credit or debit a wallet, with a reason and a name on it.
 *
 * Replaces SQL typed against production — which is how September's goodwill
 * refunds and corrections were done — and the old `users/:id/credit`, which
 * wrote a DEPOSIT and so counted money nobody paid in as money paid in.
 *
 * Each adjustment is one `adjustment` ledger row and one balance_adjustments
 * row, written together under the user's row lock. Nothing is sent to the
 * customer; the only trace they see is a history line with neutral wording.
 */
@ApiTags("admin")
@ApiBearerAuth()
@UseGuards(JwtAuthGuard, AdminGuard)
@Controller("admin/adjustments")
export class AdminAdjustmentsController {
  constructor(
    @InjectDataSource() private readonly dataSource: DataSource,
    private readonly audit: AuditService,
    @Optional() private readonly redis?: RedisService,
    @Optional() private readonly sse?: SseService,
  ) {}

  @Post("preview")
  @HttpCode(200)
  @ApiOperation({ summary: "What an adjustment would do, without doing it" })
  async preview(@Body() dto: AdjustmentPreviewDto) {
    const c = await this.check(this.dataSource.manager, dto);
    return {
      user: c.user,
      currency: dto.currency,
      amount: dto.amount,
      balance: c.balance,
      after: c.after,
      defaultUserNote: dto.amount > 0 ? DEFAULT_USER_NOTE.credit : DEFAULT_USER_NOTE.debit,
    };
  }

  @Post()
  @HttpCode(200)
  @ApiOperation({ summary: "Credit or debit a wallet with a recorded reason" })
  async create(@Body() dto: CreateAdjustmentDto, @Request() req: any) {
    const existing = await this.findByRequest(dto.requestId);
    if (existing) return { ...this.view(existing), duplicate: true };

    const note = dto.note.trim();
    const userNote =
      dto.userNote?.trim() ||
      (dto.amount > 0 ? DEFAULT_USER_NOTE.credit : DEFAULT_USER_NOTE.debit);
    const adminId: string = req.user.userId;

    let saved: BalanceAdjustment;
    try {
      saved = await this.dataSource.transaction(async (em) => {
        // Same first lock as every ledger writer, so the balance read below is
        // the balance the row is written against.
        await em
          .getRepository(User)
          .createQueryBuilder("u")
          .setLock("pessimistic_write")
          .where("u.id = :id", { id: dto.userId })
          .getOne();

        const { balance, after } = await this.check(em, dto);

        const tx = await em.save(
          Transaction,
          em.create(Transaction, {
            type: TransactionType.ADJUSTMENT,
            amount: dto.amount,
            currency: dto.currency,
            balanceBefore: balance,
            balanceAfter: after,
            userId: dto.userId,
            isBonus: false,
            note: userNote,
          }),
        );

        return em.save(
          BalanceAdjustment,
          em.create(BalanceAdjustment, {
            userId: dto.userId,
            currency: dto.currency,
            amount: dto.amount,
            reason: dto.reason,
            note,
            userNote,
            reference: dto.reference?.trim() || null,
            adminId,
            transactionId: tx.id,
            requestId: dto.requestId,
            balanceBefore: balance,
            balanceAfter: after,
          }),
        );
      });
    } catch (e: any) {
      // Two submits of the same form racing: the loser hits the unique
      // requestId, its whole transaction rolls back, and it returns the
      // winner's row — so the money moved exactly once either way.
      if (e?.code === "23505" && String(e?.detail ?? e?.message).includes("requestId")) {
        const winner = await this.findByRequest(dto.requestId);
        if (winner) return { ...this.view(winner), duplicate: true };
      }
      throw e;
    }

    await this.redis?.del(`oro:cache:balance:${dto.userId}`).catch(() => undefined);
    this.sse?.emit(dto.userId, "balance:updated", { adjustmentId: saved.id });

    await this.audit.log({
      adminId,
      isAdmin: true,
      action: AuditAction.BALANCE_ADJUST,
      entityType: "user",
      entityId: dto.userId,
      before: { balance: Number(saved.balanceBefore), currency: dto.currency },
      after: {
        balance: Number(saved.balanceAfter),
        amount: dto.amount,
        reason: dto.reason,
        note,
        userNote,
        reference: saved.reference,
        adjustmentId: saved.id,
        transactionId: saved.transactionId,
      },
      ipAddress: req.ip,
    });

    return { ...this.view(saved), duplicate: false };
  }

  @Get()
  @ApiOperation({ summary: "Adjustments, newest first, optionally for one user" })
  async list(
    @Query("userId") userId?: string,
    @Query("page") pageRaw?: string,
    @Query("limit") limitRaw?: string,
  ) {
    const limit = Math.min(Math.max(Number(limitRaw) || 50, 1), 200);
    const page = Math.max(Number(pageRaw) || 1, 1);
    const params: unknown[] = [];
    let where = "";
    if (userId) {
      if (!/^[0-9a-f-]{36}$/i.test(userId)) throw new BadRequestException("Bad userId");
      params.push(userId);
      where = `WHERE a."userId" = $1`;
    }
    const rows: any[] = await this.dataSource.query(
      `SELECT a.*, u.username, u."firstName",
              ad.username AS "adminUsername", ad."firstName" AS "adminFirstName",
              COUNT(*) OVER() AS "total"
         FROM balance_adjustments a
         JOIN users u ON u.id = a."userId"
         LEFT JOIN users ad ON ad.id = a."adminId"
         ${where}
        ORDER BY a."createdAt" DESC
        LIMIT ${limit} OFFSET ${(page - 1) * limit}`,
      params,
    );
    // Per currency, never summed across: there is no rate between them.
    const totals: any[] = await this.dataSource.query(
      `SELECT a.currency,
              COALESCE(SUM(a.amount) FILTER (WHERE a.amount > 0), 0) AS credited,
              COALESCE(SUM(-a.amount) FILTER (WHERE a.amount < 0), 0) AS debited,
              COUNT(*)::int AS count
         FROM balance_adjustments a ${where}
        GROUP BY a.currency`,
      params,
    );
    return {
      page,
      limit,
      total: rows.length ? Number(rows[0].total) : 0,
      totals: totals.map((t) => ({
        currency: t.currency,
        credited: Number(t.credited),
        debited: Number(t.debited),
        count: t.count,
      })),
      adjustments: rows.map((r) => ({
        ...this.view(r),
        username: r.username ?? null,
        firstName: r.firstName ?? null,
        admin: r.adminUsername ? `@${r.adminUsername}` : (r.adminFirstName ?? r.adminId),
      })),
    };
  }

  /**
   * Everything that has to hold before money moves, read against `em` so the
   * write path checks the balance it is about to write against.
   */
  private async check(
    em: EntityManager,
    dto: { userId: string; currency: string; amount: number },
  ): Promise<Checked> {
    const { userId, currency, amount } = dto;
    const decimals = CURRENCY_DECIMALS[currency];
    if (decimals === undefined) throw new BadRequestException("currency must be BTN or USDT");

    if (!Number.isFinite(amount) || amount === 0) {
      throw new BadRequestException("Amount must be a non-zero number");
    }
    // Reject rather than round: a silently rounded adjustment is not the one
    // the admin approved.
    const scaled = Math.abs(amount) * 10 ** decimals;
    if (Math.abs(scaled - Math.round(scaled)) > 1e-6) {
      throw new BadRequestException(
        `${currency} amounts have at most ${decimals} decimal places`,
      );
    }
    const max = ADJUSTMENT_MAX[currency];
    if (Math.abs(amount) > max) {
      throw new BadRequestException(
        `A single adjustment is limited to ${max.toLocaleString("en-US")} ${currency}`,
      );
    }

    const user = await em.getRepository(User).findOne({
      where: { id: userId },
      select: ["id", "username", "firstName", "currency", "kycStatus", "dkAccountNumber"],
    });
    if (!user) throw new NotFoundException("User not found");

    const balance = await ledgerBalance(em, userId, currency);
    // A wallet this account cannot normally hold is still correctable if it
    // already has money in it — that is exactly when a correction is needed.
    if (!allowedCurrencies(user as any).includes(currency) && balance === 0) {
      throw new BadRequestException(`This account has no ${currency} wallet`);
    }

    const after = Number((balance + amount).toFixed(decimals + 3));
    if (after < 0) {
      throw new BadRequestException(
        `That would leave the wallet at ${after} ${currency}. ` +
          `The most that can be taken back is ${Math.max(balance, 0)} ${currency}.`,
      );
    }
    return {
      user: {
        id: user.id,
        username: user.username,
        firstName: user.firstName,
        currency: user.currency,
      },
      balance,
      after,
    };
  }

  private findByRequest(requestId: string) {
    return this.dataSource
      .getRepository(BalanceAdjustment)
      .findOne({ where: { requestId } });
  }

  private view(a: any) {
    return {
      id: a.id,
      userId: a.userId,
      currency: a.currency,
      amount: Number(a.amount),
      reason: a.reason,
      reasonLabel: ADJUSTMENT_REASONS[a.reason as AdjustmentReason] ?? a.reason,
      note: a.note,
      userNote: a.userNote,
      reference: a.reference ?? null,
      adminId: a.adminId,
      transactionId: a.transactionId,
      balanceBefore: Number(a.balanceBefore),
      balanceAfter: Number(a.balanceAfter),
      createdAt: a.createdAt,
    };
  }
}
